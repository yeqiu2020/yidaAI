#!/usr/bin/env node
/**
 * generate-skill-index.js — 自动从 SKILL.md 目录生成能力表
 *
 * 遍历 .agents/skills/ 下所有子目录，读取 SKILL.md 的 frontmatter 和标题，
 * 自动生成 Markdown 格式的 Skill 能力索引表。
 *
 * 用法:
 *   node scripts/generate-skill-index.js           # 输出到 stdout
 *   node scripts/generate-skill-index.js --update   # 直接更新 README.md
 *
 * 创建日期: 2026-07-10 (Phase 1)
 */

'use strict';

const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const SKILLS_DIR = path.join(PROJECT_ROOT, '.agents', 'skills');
const SKILL_CONFIG_PATH = path.join(SKILLS_DIR, 'skill-config.json');

// 标记为非有效的目录名（demo / placeholder），须与 skill-config.json 的 exemptedSkills（唯一事实源，含豁免理由）保持一致
const NON_EFFECTIVE_DIRS = new Set([
  'hello-world-custom', // demo skill
  'skill-self-improve', // placeholder (no SKILL.md)
  'knowledge-base', // placeholder (no SKILL.md)
]);

/**
 * 解析 SKILL.md frontmatter 和标题
 * @param {string} filePath - SKILL.md 文件路径
 * @returns {{ title: string, description: string, trigger: string, hasSkillMd: boolean }}
 */
function parseSkillMd(filePath) {
  if (!fs.existsSync(filePath)) {
    return { title: '', description: '', trigger: '', hasSkillMd: false };
  }

  const content = fs.readFileSync(filePath, 'utf-8');
  const result = { title: '', description: '', trigger: '', hasSkillMd: true };

  // 提取第一个 # 标题
  const titleMatch = content.match(/^#\s+(.+)$/m);
  if (titleMatch) {
    result.title = titleMatch[1].trim();
  }

  // 提取 frontmatter 中的 description 和 trigger
  const fmMatch = content.match(/^---\n([\s\S]*?)\n---/);
  if (fmMatch) {
    const fm = fmMatch[1];
    const descMatch = fm.match(/^description:\s*(.+)$/m);
    if (descMatch) {
      result.description = descMatch[1].trim().replace(/^["']|["']$/g, '');
    }
    const triggerMatch = fm.match(/^trigger:\s*(.+)$/m);
    if (triggerMatch) {
      result.trigger = triggerMatch[1].trim().replace(/^["']|["']$/g, '');
    }
  }

  // 如果没有 frontmatter description，尝试从第二行获取
  if (!result.description) {
    const lines = content.split('\n').filter((l) => l.trim() && !l.startsWith('#') && !l.startsWith('>') && !l.startsWith('---'));
    if (lines.length > 0) {
      result.description = lines[0].trim().substring(0, 80);
    }
  }

  return result;
}

/**
 * 生成 Skill 索引表
 * @returns {{ markdown: string, totalDirs: number, effectiveCount: number, skills: Array }}
 */
function generateIndex() {
  const dirs = fs.readdirSync(SKILLS_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  const skills = [];
  let effectiveCount = 0;

  for (const dirName of dirs) {
    const skillMdPath = path.join(SKILLS_DIR, dirName, 'SKILL.md');
    const info = parseSkillMd(skillMdPath);
    const isEffective = info.hasSkillMd && !NON_EFFECTIVE_DIRS.has(dirName);

    if (isEffective) {
      effectiveCount++;
    }

    skills.push({
      dirName,
      title: info.title || dirName,
      description: info.description || (info.hasSkillMd ? '' : '（占位目录）'),
      trigger: info.trigger || '',
      hasSkillMd: info.hasSkillMd,
      isEffective,
    });
  }

  // 生成 Markdown 表格
  const lines = [
    `<!-- Auto-generated by scripts/generate-skill-index.js | 生成日期: ${new Date().toISOString().split('T')[0]} -->`,
    '',
    `> 共 ${dirs.length} 个目录，${effectiveCount} 个有效 Skill`,
    '',
    '| 目录名 | 标题 | 说明 | 触发词 | 状态 |',
    '| ------ | ---- | ---- | ------ | ---- |',
  ];

  for (const s of skills) {
    const status = s.isEffective ? '✅ 有效' : (s.hasSkillMd ? '⚠️ Demo' : '⚪ 占位');
    const triggerCol = s.trigger ? s.trigger.replace(/\|/g, '\\|') : '-';
    const descCol = s.description ? s.description.replace(/\|/g, '\\|') : '-';
    const titleCol = s.title ? s.title.replace(/\|/g, '\\|') : s.dirName;
    lines.push(`| ${s.dirName} | ${titleCol} | ${descCol} | ${triggerCol} | ${status} |`);
  }

  return {
    markdown: lines.join('\n'),
    totalDirs: dirs.length,
    effectiveCount,
    skills,
  };
}

/**
 * 生成易混技能消歧表（读取 skill-config.json 的 disambiguationGroups）
 * 纯附加能力：配置缺失或无该字段时返回空串，不影响主能力表生成。
 * @returns {string} Markdown 消歧表；无数据时为空串
 */
function generateDisambiguationTable() {
  if (!fs.existsSync(SKILL_CONFIG_PATH)) {
    return '';
  }
  let config;
  try {
    config = JSON.parse(fs.readFileSync(SKILL_CONFIG_PATH, 'utf-8'));
  } catch (e) {
    return '';
  }
  const groups = Array.isArray(config.disambiguationGroups) ? config.disambiguationGroups : [];
  if (groups.length === 0) {
    return '';
  }

  const lines = [
    `<!-- Auto-generated by scripts/generate-skill-index.js | 生成日期: ${new Date().toISOString().split('T')[0]} -->`,
    '',
    '> 易混技能消歧表：触发词相近时按下表判断该用哪个（use=应触发，避免=易误触发但不该用）。',
    '',
  ];
  for (const g of groups) {
    lines.push(`### ${g.topic}`);
    lines.push('');
    lines.push('| 用户意图 | 应触发 | 避免误触发 |');
    lines.push('| -------- | ------ | ---------- |');
    for (const r of (g.rules || [])) {
      const when = (r.when || '').replace(/\|/g, '\\|');
      const use = (r.use || '').replace(/\|/g, '\\|');
      const not = (r.not || '').replace(/\|/g, '\\|');
      lines.push(`| ${when} | \`${use}\` | ${not || '-'} |`);
    }
    lines.push('');
  }
  return lines.join('\n').trimEnd();
}

// ===== 主流程 =====
const args = process.argv.slice(2);
const shouldUpdate = args.includes('--update') || args.includes('-u');

const result = generateIndex();
const disambiguation = generateDisambiguationTable();

if (shouldUpdate) {
  // 更新 README.md 中的能力表
  const readmePath = path.join(PROJECT_ROOT, 'README.md');
  if (fs.existsSync(readmePath)) {
    let readme = fs.readFileSync(readmePath, 'utf-8');

    // 替换 <!-- SKILL_INDEX_START --> 到 <!-- SKILL_INDEX_END --> 之间的内容
    const startMarker = '<!-- SKILL_INDEX_START -->';
    const endMarker = '<!-- SKILL_INDEX_END -->';

    if (readme.includes(startMarker) && readme.includes(endMarker)) {
      const before = readme.substring(0, readme.indexOf(startMarker) + startMarker.length);
      const after = readme.substring(readme.indexOf(endMarker));
      readme = before + '\n\n' + result.markdown + '\n\n' + after;
      fs.writeFileSync(readmePath, readme, 'utf-8');
      console.log(`✅ README.md 已更新 (${result.totalDirs} 目录 / ${result.effectiveCount} 有效)`);
    } else {
      console.log('⚠️ README.md 中未找到 SKILL_INDEX 标记，请手动添加以下标记:');
      console.log(`   ${startMarker}`);
      console.log(`   ${endMarker}`);
      console.log('\n' + result.markdown);
    }

    // 同步消歧表（独立标记，与主能力表互不影响）
    if (disambiguation) {
      readme = fs.readFileSync(readmePath, 'utf-8');
      const dStart = '<!-- DISAMBIGUATION_START -->';
      const dEnd = '<!-- DISAMBIGUATION_END -->';
      if (readme.includes(dStart) && readme.includes(dEnd)) {
        const before = readme.substring(0, readme.indexOf(dStart) + dStart.length);
        const after = readme.substring(readme.indexOf(dEnd));
        readme = before + '\n\n' + disambiguation + '\n\n' + after;
        fs.writeFileSync(readmePath, readme, 'utf-8');
        console.log('✅ README.md 消歧表已更新');
      } else {
        console.log('⚠️ README.md 中未找到 DISAMBIGUATION 标记，请手动添加以下标记:');
        console.log(`   ${dStart}`);
        console.log(`   ${dEnd}`);
      }
    }
  } else {
    console.log('⚠️ README.md 不存在');
    console.log('\n' + result.markdown);
  }
} else {
  // 输出到 stdout
  console.log(result.markdown);
  if (disambiguation) {
    console.log('\n\n## 易混技能消歧表\n');
    console.log(disambiguation);
  }
  console.error(`\n统计: ${result.totalDirs} 目录 / ${result.effectiveCount} 有效 Skill`);
}
