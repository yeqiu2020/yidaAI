function buildMerges(rows) {
  const merges = [];
  let startDataIdx = 0;
  for (let i = 1; i <= rows.length; i++) {
    const isEnd = i === rows.length;
    const groupChanged = !isEnd && rows[i][0] !== '';
    if (isEnd || groupChanged) {
      if (i - 1 > startDataIdx) {
        merges.push({ s: { c: 0, r: startDataIdx + 1 }, e: { c: 0, r: (i - 1) + 1 } });
      }
      startDataIdx = i;
    }
  }
  return merges;
}

function makeWorkbook(dataRows) {
  const aoa = [HEADER, ...dataRows];
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  ws['!ref'] = XLSX.utils.encode_range({ s: { c: 0, r: 0 }, e: { c: 7, r: dataRows.length } });
  ws['!merges'] = buildMerges(dataRows);
  ws['!cols'] = [
    { wch: 14 }, { wch: 10 }, { wch: 16 }, { wch: 70 },
    { wch: 14 }, { wch: 70 }, { wch: 14 }, { wch: 60 },
  ];
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, '表单清单');
  return wb;
}

