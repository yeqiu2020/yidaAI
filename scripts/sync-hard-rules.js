'use strict';

/**
 * sync-hard-rules.js - 把集成自动化硬规则从权威源分发到各 AI 工具的规则入口
 *
 * 权威源（唯一可手改）：.agents/skills/integration/references/集成自动化硬规则.md
 * 同步目标（自动生成，勿手改）：
 *   - .trae/rules/宜搭集成自动化硬规则.md          Trae
 *   - .cursor/rules/yida-integration-hard-rules.mdc Cursor（alwaysApply）
 *   - AGENTS.md                                     通用标准（Codex/Zed/Amp/新版Cursor等）
 *   - CLAUDE.md                                     Claude Code
 *
 * AGENTS.md / CLAUDE.md 采用标记块管理，只替换标记之间的内容，不影响文件其他部分。
 *
 * 运行：node scripts/sync-hard-rules.js
 */

const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(PROJECT_ROOT, '.agents/skills/integration/references/集成自动化硬规则.md');

const BLOCK_BEGIN = '<!-- BEGIN yida-integration-hard-rules (generated by scripts/sync-hard-rules.js, do not edit) -->';
const BLOCK_END = '<!-- END yida-integration-hard-rules -->';

function readSource() {
  const raw = fs.readFileSync(SOURCE, 'utf8');
  // 去掉源文件里"如何同步"的元注释，目标文件有自己的生成头
  return raw
    .split('\n')
    .filter((line) => !line.startsWith('<!-- 权威源文件') && !line.startsWith('<!-- 同步目标'))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim() + '\n';
}

function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function writeGeneratedFile(relPath, content) {
  const target = path.join(PROJECT_ROOT, relPath);
  ensureDir(target);
  fs.writeFileSync(target, content, 'utf8');
  console.log('已同步: ' + relPath);
}

// 在已有文件中替换/追加标记块（用于 AGENTS.md / CLAUDE.md，不破坏文件其余内容）
function upsertBlock(relPath, blockContent, createHeader) {
  const target = path.join(PROJECT_ROOT, relPath);
  const block = BLOCK_BEGIN + '\n\n' + blockContent + '\n' + BLOCK_END + '\n';
  let fileContent;
  if (fs.existsSync(target)) {
    const existing = fs.readFileSync(target, 'utf8');
    const beginIdx = existing.indexOf(BLOCK_BEGIN);
    const endIdx = existing.indexOf(BLOCK_END);
    if (beginIdx >= 0 && endIdx > beginIdx) {
      fileContent = existing.slice(0, beginIdx) + block + existing.slice(endIdx + BLOCK_END.length + 1);
    } else {
      fileContent = existing.replace(/\s*$/, '\n\n') + block;
    }
  } else {
    fileContent = createHeader + '\n' + block;
  }
  fs.writeFileSync(target, fileContent, 'utf8');
  console.log('已同步: ' + relPath + '（标记块）');
}

function main() {
  if (!fs.existsSync(SOURCE)) {
    console.error('错误: 权威源不存在: ' + SOURCE);
    process.exit(1);
  }
  const rules = readSource();
  const generatedNote =
    '<!-- 本文件由 scripts/sync-hard-rules.js 自动生成，请勿直接修改。 -->\n' +
    '<!-- 权威源: .agents/skills/integration/references/集成自动化硬规则.md，改完源文件后运行 node scripts/sync-hard-rules.js -->\n\n';

  // 1. Trae
  writeGeneratedFile('.trae/rules/宜搭集成自动化硬规则.md', generatedNote + rules);

  // 2. Cursor（.mdc 需要 frontmatter，alwaysApply 使规则每轮生效）
  const cursorFrontmatter =
    '---\n' +
    'description: 宜搭集成自动化（逻辑流）生成硬规则，防止AI产出保存成功但不工作的废流\n' +
    'alwaysApply: true\n' +
    '---\n\n';
  writeGeneratedFile('.cursor/rules/yida-integration-hard-rules.mdc', cursorFrontmatter + generatedNote + rules);

  // 3. AGENTS.md（多工具通用标准，块头部带权威源路径与同步命令，与 .cursor 副本一致）
  upsertBlock('AGENTS.md', generatedNote + rules, '# AGENTS.md - 本工程 AI 协作规则\n');

  // 4. CLAUDE.md（Claude Code）
  upsertBlock('CLAUDE.md', generatedNote + rules, '# CLAUDE.md - 本工程 AI 协作规则\n');

  console.log('\n同步完成。权威源: .agents/skills/integration/references/集成自动化硬规则.md');
}

main();
