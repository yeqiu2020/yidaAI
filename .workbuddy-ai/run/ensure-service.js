#!/usr/bin/env node
/**
 * ensure-service.js — 宜搭本地服务「确保运行」唯一入口（幂等 + 自验证）
 * ---------------------------------------------------------------------------
 * 为什么需要它（2026-10-17 事故）：
 *   在 WorkBuddy / Trae 等 Agent 宿主里，命令沙箱用 Job Object 包裹整条命令的进程树，
 *   命令结束即 kill-on-close。`server_manager.js start` 虽然 spawn 了 detached 子进程，
 *   但子进程仍在宿主 Job 内 → 命令一结束 8080/3457 立刻被回收，
 *   表现为「启动日志全绿、浏览器打开却是空白 / 暂无数据」。
 *   实测唯一可靠的脱离方式是让 explorer.exe 去拉起脚本（父进程变成资源管理器，脱离 Job）。
 *   schtasks 在本机被安全中心 Program Blacklist 拦截，不可用。
 *
 * 用法：
 *   node .workbuddy-ai/run/ensure-service.js            # 确保服务在跑（默认，幂等）
 *   node .workbuddy-ai/run/ensure-service.js status      # 只查状态
 *   node .workbuddy-ai/run/ensure-service.js stop        # 停止
 *   node .workbuddy-ai/run/ensure-service.js --json      # 末尾只输出 YIDA_READY 单行 JSON
 *
 * 退出码：0 = 服务已就绪；1 = 未能拉起（会给出用户可执行的手动兜底方案）
 */
'use strict';

const http = require('http');
const os = require('os');
const path = require('path');
const fs = require('fs');
const { spawn, spawnSync } = require('child_process');

const PROJECT_ROOT = path.resolve(__dirname, '..', '..');
const PROJECT_DIR_NAME = path.basename(PROJECT_ROOT);
const { serviceLocations } = require('../../lib/local-service/locations');
const locations = serviceLocations(PROJECT_ROOT);
const STATIC_ROOT = locations.staticRoot;
const HTTP_PORT = 8080;
const SYNC_PORT = 3457;
const PORTAL_URL = locations.portalEncoded;
const PORTAL_PATH = new URL(PORTAL_URL).pathname;
const MARKDOWN = locations.markdown;
const LAUNCHER_BAT = path.join(PROJECT_ROOT, 'start-local-service.bat');
const LOG_FILE = path.join(PROJECT_ROOT, 'service-start.log');

const arg = (process.argv[2] || 'start').toLowerCase();
const JSON_ONLY = process.argv.includes('--json');

const log = (...a) => { if (!JSON_ONLY) console.log(...a); };

/** 直连探测（不走系统代理；本机代理会把 127.0.0.1 请求变成 502 误导判断） */
function probe(port, urlPath, timeout = 1500) {
  return new Promise((resolve) => {
    const req = http.get({ host: '127.0.0.1', port, path: urlPath, timeout }, (res) => {
      let bytes = 0;
      const chunks = [];
      res.on('data', (c) => { bytes += c.length; chunks.push(c); });
      res.on('end', () => {
        let json;
        try { json = JSON.parse(Buffer.concat(chunks).toString('utf8')); } catch (_) {}
        resolve({ ok: res.statusCode >= 200 && res.statusCode < 400, code: res.statusCode, bytes, json });
      });
    });
    req.on('timeout', () => { req.destroy(); resolve({ ok: false, code: 0, bytes: 0, err: 'timeout' }); });
    req.on('error', (e) => resolve({ ok: false, code: 0, bytes: 0, err: e.code || e.message }));
  });
}

async function snapshot() {
  const [page, sync, staticHealth] = await Promise.all([
    // 路径含中文，必须 encodeURI，否则 http.get 直接抛 "Request path contains unescaped characters"
    probe(HTTP_PORT, PORTAL_PATH),
    probe(SYNC_PORT, '/health'),
    probe(HTTP_PORT, '/__yida_health'),
  ]);
  page.ok = page.ok && !!(staticHealth.json && staticHealth.json.securityPatch === 'enabled');
  sync.ok = sync.ok && !!(sync.json && sync.json.securityPatch === 'enabled');
  return { page, sync, ready: page.ok && sync.ok };
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** 让 3457 同步服务帮忙拉起服务（它在宿主 Job 之外，spawn 的子进程能常驻） */
async function launchViaSyncService() {
  try {
    const { requestJson } = require('../../lib/local-service/client');
    const r = await requestJson('http://127.0.0.1:' + SYNC_PORT, '/ensure-service?projectDir=' + encodeURIComponent(PROJECT_DIR_NAME), undefined, 'GET');
    return { ok: r.status >= 200 && r.status < 300 && !!(r.json && r.json.success), body: r.json };
  } catch (e) { return { ok: false, reason: e.message }; }
}

/**
 * 中立启动器：把「启动脚本」放到用户目录（工作区之外）再让 explorer 拉起。
 *
 * 为什么不在项目目录里直接 explorer 启动 .bat（2026-10-17 实测）：
 *   本机的安全策略会拦截**工作区目录内**的脚本经 ShellExecute 启动，
 *   弹「打开文件 - 安全警告」，必须人工点「运行」才执行 —— 于是自动化全废，
 *   多次调用还会堆积弹窗把 explorer 拖到失能。
 *   实测同一个 .bat 放到 %LOCALAPPDATA%\Temp 下经 explorer 启动**立即执行、无弹窗**。
 *   因此每次启动前现写一份中立启动器（内容跟随项目路径，不会失效）。
 */
const NEUTRAL_DIR = path.join(process.env.LOCALAPPDATA || os.tmpdir(), 'YidaService');
const NEUTRAL_BAT = path.join(NEUTRAL_DIR, 'start-yida.cmd');

function ensureNeutralLauncher() {
  try {
    fs.mkdirSync(NEUTRAL_DIR, { recursive: true });
    const lines = [
      '@echo off',
      'rem auto-generated by ensure-service.js - do not edit',
      `cd /d "${PROJECT_ROOT}"`,
      `echo [%date% %time%] neutral-launcher start >> "${path.join(NEUTRAL_DIR, 'start.log')}"`,
      `node ".agents\\skills\\server-manager\\scripts\\server_manager.js" start >> "${path.join(NEUTRAL_DIR, 'start.log')}" 2>&1`,
      `echo [%date% %time%] neutral-launcher exit=%ERRORLEVEL% >> "${path.join(NEUTRAL_DIR, 'start.log')}"`,
      '',
    ];
    const content = lines.join('\r\n') + '\r\n';
    // 必须按 GBK 写入：cmd.exe 用系统 ANSI 代码页(936)读批处理，
    // 写 UTF-8 会让项目路径里的中文变成乱码 → cd 失败 → node 找不到脚本（2026-10-17 实测踩过）
    let iconv = null;
    try { iconv = require('iconv-lite'); } catch (_) { iconv = null; }
    if (iconv) {
      fs.writeFileSync(NEUTRAL_BAT, iconv.encode(content, 'gbk'));
    } else {
      throw new Error('缺少 iconv-lite，请先 npm install');
    }
    return NEUTRAL_BAT;
  } catch (e) {
    return null;
  }
}

/** 用 explorer.exe 拉起中立启动器（工作区外，无安全警告弹窗） */
function launchViaExplorer() {
  const bat = ensureNeutralLauncher();
  if (!bat) {
    return { ok: false, reason: '无法生成启动器，且项目内启动脚本不存在' };
  }
  try {
    const child = spawn('explorer.exe', [bat], {
      detached: true,
      stdio: 'ignore',
      windowsHide: true,
      cwd: path.dirname(bat),
    });
    child.unref();
    return { ok: true, pid: child.pid, launcher: bat };
  } catch (e) {
    return { ok: false, reason: e.message };
  }
}

function runServerManager(sub) {
  const script = path.join(PROJECT_ROOT, '.agents', 'skills', 'server-manager', 'scripts', 'server_manager.js');
  const r = spawnSync(process.execPath, [script, sub], { cwd: PROJECT_ROOT, encoding: 'utf8', timeout: 120000 });
  return { code: r.status, out: (r.stdout || '') + (r.stderr || '') };
}

function printReport(snap, extra) {
  const icon = (b) => (b ? '🟢 运行中' : '🔴 未启动');
  log('');
  log('┌─────────────────────┬────────┬──────────────────────────┐');
  log(`│ HTTP 静态服务       │ ${HTTP_PORT}   │ ${icon(snap.page.ok).padEnd(24)}│`);
  log(`│ 同步配置服务        │ ${SYNC_PORT}   │ ${icon(snap.sync.ok).padEnd(24)}│`);
  log('└─────────────────────┴────────┴──────────────────────────┘');
  if (snap.page.ok) log(`   页面: HTTP ${snap.page.code}, ${snap.page.bytes} 字节`);
  if (extra) log(`   ${extra}`);
  log('');
  log(MARKDOWN);
}

async function main() {
  if (arg === 'status') {
    const snap = await snapshot();
    printReport(snap);
    emitJson(snap, 'status');
    process.exit(snap.ready ? 0 : 1);
  }

  if (arg === 'stop') {
    const r = runServerManager('stop');
    await sleep(1200);
    const snap = await snapshot();
    printReport(snap, `已执行停止（exit=${r.code}）`);
    emitJson(snap, 'stop');
    process.exit(0);
  }

  // start（幂等）—— 三条路径，按可靠性排序
  let snap = await snapshot();
  if (snap.ready) {
    printReport(snap, '服务原本就在运行，无需重复启动。');
    emitJson(snap, 'already-running');
    process.exit(0);
  }

  // 路径 A（首选，无弹窗）：3457 还活着 → 让它在宿主 Job 之外 spawn server_manager start
  if (snap.sync.ok) {
    log('检测到 3457 同步服务在线，通过它拉起缺失的服务（不依赖任何系统弹窗）…');
    const r = await launchViaSyncService();
    if (!r.ok) log(`   ⚠️  请求失败（${r.reason}），改走兜底路径…`);
  } else {
    // 路径 B（兜底）：3457 也没了 → 用 explorer 拉起「工作区外的中立启动器」（实测无安全警告弹窗）
    log('3457 同步服务也不在线，改用 explorer 拉起中立启动器…');
    const launch = launchViaExplorer();
    if (launch.ok) {
      log(`   启动器: ${launch.launcher}`);
    } else {
      log(`   ❌ explorer 拉起失败：${launch.reason}`);
    }
  }

  // 轮询最多 40 秒（同步服务首次启动可能要几秒）
  const deadline = Date.now() + 40000;
  let lastLog = 0;
  while (Date.now() < deadline) {
    await sleep(1000);
    snap = await snapshot();
    if (snap.ready) break;
    if (Date.now() - lastLog > 6000) {
      log(`   …等待中（页面 ${snap.page.ok ? 'OK' : '未响应'} / 同步 ${snap.sync.ok ? 'OK' : '未响应'}）`);
      lastLog = Date.now();
    }
  }

  if (snap.ready) {
    printReport(snap, '✅ 服务已就绪，且已确认进程常驻（不受本命令退出影响）。');
    emitJson(snap, 'started');
    process.exit(0);
  }

  printReport(snap, '❌ 40 秒内未就绪。请手动双击 start-local-service.bat，或查看 service-start.log。');
  emitJson(snap, 'timeout');
  process.exit(1);
}

function emitJson(snap, phase) {
  const payload = {
    ok: snap.ready,
    phase,
    projectRoot: PROJECT_ROOT,
    projectDirName: PROJECT_DIR_NAME,
    staticRoot: STATIC_ROOT,
    http: { port: HTTP_PORT, running: snap.page.ok, code: snap.page.code, bytes: snap.page.bytes },
    sync: { port: SYNC_PORT, running: snap.sync.ok, code: snap.sync.code },
    url: { portal: PORTAL_URL },
    markdown: MARKDOWN,
    logFile: LOG_FILE,
  };
  console.log('YIDA_READY ' + JSON.stringify(payload));
}

main().catch((e) => {
  console.error('ensure-service 异常:', e && e.message);
  process.exit(1);
});
